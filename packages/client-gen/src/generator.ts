import type { AnchorIdl } from '@solana-web-ide/anchor-support';

/**
 * Generate a TypeScript client SDK from an Anchor IDL.
 * Returns a TypeScript source string that can be shown in the IDE
 * or downloaded as a .ts file.
 *
 * Phase 4 implementation.
 */
export function generateClient(idl: AnchorIdl): string {
  const lines: string[] = [
    `// Auto-generated by solana-web-ide client-gen`,
    `// Program: ${idl.name} v${idl.version}`,
    ``,
    `import { PublicKey, TransactionInstruction } from '@solana/web3.js';`,
    ``,
  ];

  for (const ix of idl.instructions) {
    lines.push(`/** ${ix.docs?.join(' ') ?? ix.name} */`);
    lines.push(`export function build${capitalize(ix.name)}Ix(`);
    for (const arg of ix.args) {
      lines.push(`  ${arg.name}: unknown, // TODO: type ${JSON.stringify(arg.type)}`);
    }
    lines.push(`): TransactionInstruction {`);
    lines.push(`  void ${ix.args.map((a) => a.name).join(', ') || '{}'}; // TODO: encode args`);
    lines.push(`  throw new Error('Not yet implemented — Phase 4');`);
    lines.push(`}`);
    lines.push(``);
  }

  return lines.join('\n');
}

function capitalize(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}
